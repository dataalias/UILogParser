import csv
import ipaddress
import json

def get_abusive_ips(file_name, min_score=50, min_count=100):
    """
    Purpose: Reads the abuse csv (output of iprep.abuse_scroing) and returns every IP
                with abuseConfidenceScore >= min_score and count > min_count.
    """
    ips = []

    with open(file_name, "r", newline='') as input_file:
        for row in csv.DictReader(input_file):
            try:
                score = int(row['abuseConfidenceScore'])
                count = int(row['count'])
            except (KeyError, ValueError, TypeError):
                continue

            if score >= min_score and count > min_count:
                ips.append(row['ip'])

    return ips


def abusive_ips_to_mongo_script(file_name, script_file_name=None, list_name="DenyListIPAddresses",
                                min_score=50, min_count=100):
    """
    Purpose: Builds a mongo script that adds the abusive IPs to the firewall group list_name
                (see docs/Mongo.md). Run it on the UDM Pro with:
                    mongo --port 27117 ace < <script>.js
                The controller must then be restarted (systemctl restart unifi).
    """
    if script_file_name is None:
        script_file_name = file_name.replace('.csv', '_denylist.js')

    # validate so nothing but real IPv4 addresses ends up in the script
    ips = sorted({str(ipaddress.IPv4Address(ip.strip()))
                  for ip in get_abusive_ips(file_name, min_score, min_count)})

    script = """// Generated by abuse_filter.py - adds {count} IPs to {name}
var name = {name_json};
var ips = {ips_json};

var matches = db.firewallgroup.find({{"name": name}}).count();
if (matches !== 1) {{
    print("ABORT: expected 1 group named " + name + ", found " + matches);
}} else {{
    print("BACKUP:");
    printjson(db.firewallgroup.findOne({{"name": name}}));
    printjson(db.firewallgroup.updateOne(
        {{"name": name}},
        {{$addToSet: {{"group_members": {{$each: ips}}}}}}
    ));
    print("AFTER:");
    printjson(db.firewallgroup.findOne({{"name": name}}));
}}
""".format(count=len(ips), name=list_name, name_json=json.dumps(list_name),
           ips_json=json.dumps(ips, indent=4))

    with open(script_file_name, "w", newline='\n') as script_file:
        script_file.write(script)

    print("{} IPs written to {}".format(len(ips), script_file_name))
    return ips


if __name__ == "__main__":
    abusive_ips_to_mongo_script("d:\\RouterLogs\\IPs_output.csv")
